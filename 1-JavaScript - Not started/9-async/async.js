// ===================== ASYNCHRONOUS JAVASCRIPT =====================

// JavaScript has **two types of code**:

// 1. **Synchronous (normal) code** → runs immediately, line by line.
// 2. **Asynchronous (async) code** → runs later, after a slow task finishes (I/O, timers, API calls, etc.).

// What are AJAX calls?
// AJAX (Asynchronous JavaScript and XML) is a way to send and receive data from a server without reloading the page.
// AJAX (Asynchronous JavaScript And XML): Allows us to communicate with remote web servers in a asynchronous way.
// With AJAX calls, we can request data from web server dynamically.

// What is an API (Application programming interface)?
// Piece of software that can be used by another pience of software, in order to allow application to talk to each other.
